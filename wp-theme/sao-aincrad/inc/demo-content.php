/**
 * Створити запис, якщо запису з таким slug ще немає.
 *
 * @return int ID запису.
 */
function sao_demo_insert( $args, $meta = array(), $tags = array() ) {
	$existing = get_page_by_path( $args['post_name'], OBJECT, $args['post_type'] );
	if ( $existing ) {
		return $existing->ID;
	}

	$args = wp_parse_args(
		$args,
		array(
			'post_status' => 'publish',
			'post_author' => get_current_user_id() ? get_current_user_id() : 1,
		)
	);

	$post_id = wp_insert_post( wp_slash( $args ) );
	if ( ! $post_id || is_wp_error( $post_id ) ) {
		return 0;
	}
	foreach ( $meta as $key => $value ) {
		update_post_meta( $post_id, $key, $value );
	}
	if ( $tags ) {
		wp_set_post_tags( $post_id, $tags );
	}
	return $post_id;
}

/**
 * Абзаци тексту → блоки редактора Gutenberg.
 */
function sao_blocks( array $parts ) {
	$out = '';
	foreach ( $parts as $part ) {
		if ( is_array( $part ) ) { // [ 'h2', 'Заголовок' ] або [ 'ul', [ ... ] ]
			list( $type, $value ) = $part;
			if ( 'ul' === $type ) {
				$out .= "<!-- wp:list -->\n<ul class=\"wp-block-list\">";
				foreach ( $value as $li ) {
					$out .= "<!-- wp:list-item -->\n<li>" . $li . "</li>\n<!-- /wp:list-item -->";
				}
				$out .= "</ul>\n<!-- /wp:list -->\n\n";
			} else {
				$level = (int) substr( $type, 1 );
				$out  .= '<!-- wp:heading' . ( 2 === $level ? '' : ' {"level":' . $level . '}' ) . " -->\n<{$type} class=\"wp-block-heading\">{$value}</{$type}>\n<!-- /wp:heading -->\n\n";
			}
		} else {
			$out .= "<!-- wp:paragraph -->\n<p>{$part}</p>\n<!-- /wp:paragraph -->\n\n";
		}
	}
	return $out;
}

